// Google TV Freeplay detection.
//
// Freeplay is the free live TV of Google TV. Its channels play in the Google
// TV home screen app (the launcher), not in an app of their own. The launcher
// has no media session, so the media session gives no ad marker.
//
// The log of the capture marks no ad break either. During an ad, the launcher
// sends ad tracking requests to dai.google.com (Google Dynamic Ad Insertion),
// but only at a few points of each ad, up to 7.4 seconds apart in the
// capture. No line marks the end of the break.
//
// The ad overlay is the marker, as for YouTube and Tubi. During the show the
// screen capture is blank. During an ad break, the overlay shows a countdown
// ring at the top right, with the time left in the break, such as 1:37. The
// ring has a bright arc for the time left and a dim gray track for the rest.
// The check uses a low brightness threshold, so both parts count as bright,
// and the ring is whole at every point of the break. The time in the ring
// changes, so the mask holds no digits. The digits count as mismatches.
//
// The launcher always runs, so the detector first reads the audio focus. The
// launcher takes the audio focus when a channel starts, and gives it up when
// the player stops. The detector captures the screen only while the launcher
// holds the audio focus.

import (
	"image"
	"strings"
)

const freeplayPackage = "com.google.android.apps.tv.launcherx"

// freeplayCommand prints the audio focus stack, one line for each app that
// asked for the audio focus. The last line is the app that holds it.
const freeplayCommand = "dumpsys audio | grep -A10 'Audio Focus stack entries' | grep ' -- pack: '"

// freeplayPlaying reads the output of freeplayCommand. It is true while the
// launcher holds the audio focus, that is, while a Freeplay channel plays.
func freeplayPlaying(out string) bool {
	top := ""
	for _, line := range strings.Split(out, "\n") {
		if strings.Contains(line, " -- pack: ") {
			top = line
		}
	}
	return strings.Contains(top, " -- pack: "+freeplayPackage+" ")
}

