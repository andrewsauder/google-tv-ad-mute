// freeplayRing is the countdown ring and its search area. The search area
// allows the ring to move about 55 pixels left, 50 pixels right, 40 pixels
// up and 60 pixels down.
var freeplayRing = overlayText{
	mask: parseMask(freeplayRingMask),
	x0:   1740, x1: 1850,
	y0: 5, y1: 105,
	threshold:          32,
	maxMismatchPercent: 10,
}

// hasFreeplayCountdown reports whether the screen shows the countdown ring of
// a Freeplay ad break.
func hasFreeplayCountdown(img image.Image) bool {
	return freeplayRing.on(img)
}
