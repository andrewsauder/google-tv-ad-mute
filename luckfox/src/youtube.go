// sponsored is the word "Sponsored" and its search area. The real ads differ
// from the mask by 0.2% at most. Other screens differ by 30% or more.
var sponsored = overlayText{
	mask: parseMask(sponsoredMask),
	x0:   40, x1: 300,
	y0: 860, y1: 1057,
	threshold:          128,
	maxMismatchPercent: 10,
}

// hasSponsoredLabel reports whether the screen shows the word "Sponsored" of
// the YouTube ad overlay.
func hasSponsoredLabel(img image.Image) bool {
	return sponsored.on(img)
}
